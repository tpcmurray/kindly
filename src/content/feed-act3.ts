import type { PostDef } from './types';

// Feed posts for Acts 3 and 4 (and their reactions, plus business posts). Ids are prefixed f3_.
// Act 3 (squeeze): bitter, tired, trapped members; small businesses squeezed by reach cuts and fees.
// Act 4 (the exit): quiet, practical, grieving. The feed is sunset ~8 minutes into Act 4, so Act 4
// posts only ever show in that window. Reactions (`priority` + `after`) land right after their trigger.

type Cond = Omit<PostDef, 'id' | 'text' | 'handle' | 'kind'>;
type Row = string | [text: string, handle: string];

// Plain posts: a string, or [text, handle] for a recurring character.
function g(prefix: string, c: Cond, rows: Row[]): PostDef[] {
  return rows.map((r, i) => {
    const [text, handle] = typeof r === 'string' ? [r, undefined] : r;
    return { id: `f3_${prefix}_${i + 1}`, text, ...(handle ? { handle } : {}), ...c };
  });
}

// Business posts: [handle, text].
function biz(prefix: string, c: Cond, rows: [handle: string, text: string][]): PostDef[] {
  return rows.map(([handle, text], i) => ({ id: `f3_${prefix}_${i + 1}`, kind: 'biz' as const, handle, text, ...c }));
}

// Reactions: [trigger, text, handle?, 'biz'?]. Shown right after the trigger fires.
type R = [after: string, text: string, handle?: string, kind?: 'biz'];
function react(prefix: string, c: Cond, rows: R[]): PostDef[] {
  return rows.map(([after, text, handle, kind], i) => ({
    id: `f3_${prefix}_${i + 1}`, text, after, priority: true, ...c,
    ...(handle ? { handle } : {}), ...(kind ? { kind } : {}),
  }));
}

